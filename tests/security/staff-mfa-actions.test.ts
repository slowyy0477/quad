describe('explicit provider-owned staff TOTP enrollment', () => {
  it('returns only the owned factor ID and inert QR, not setup keys/URI/session data', async () => {
    const result = await actions.enrollStaffMfaAction(form({
      friendlyName: ' Work phone ', userId: OTHER, role: 'admin', qrCode: 'forged-client-qr',
    }))
    expect(result.status).toBe('enrolled')
    if (result.status !== 'enrolled') throw new Error('Expected fixture enrollment')
    expect(Object.keys(result).sort()).toEqual(['factorId', 'qrCode', 'status'])
    expect(result.factorId).toBe(NEW_FACTOR)
    expect(result.qrCode).toMatch(/^data:image\/svg\+xml;base64,/)
    expect(Buffer.from(result.qrCode.split(',')[1], 'base64').toString('utf8')).toContain('<svg')
    expect(Buffer.from(result.qrCode.split(',')[1], 'base64').toString('utf8')).not.toContain('Generated by SVGo')
    expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
    expect(JSON.stringify(result)).not.toContain('otpauth:')
    expect(JSON.stringify(result)).not.toContain(INITIAL)
    expect(mocks.enroll).toHaveBeenCalledWith({ factorType: 'totp', friendlyName: 'Work phone', issuer: 'Bulla' })
    expect(mocks.eq).toHaveBeenCalledWith('user_id', USER)
    expect(mocks.rpc).not.toHaveBeenCalled()
    expect(mocks.revalidatePath).toHaveBeenCalledWith('/settings/security')
    expect(mocks.unenroll).not.toHaveBeenCalled()
  })

  it.each([61, 97])('accepts the normal provider cell-grid format above the legacy QR limit (%i cells)', async modules => {
    const qr = `data:image/svg+xml;utf-8,${providerCellGrid(modules)}`
    expect(qr.length).toBeGreaterThan(256_000)
    expect(qr.length).toBeLessThan(1_048_576)
    mocks.enroll.mockImplementation(async () => {
      mocks.factors.push({ id: NEW_FACTOR, factor_type: 'totp', status: 'unverified', friendly_name: 'Work phone' })
      return { data: enrolledData(qr), error: null }
    })
    const result = await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))
    expect(result.status).toBe('enrolled')
    if (result.status !== 'enrolled') throw new Error('Expected owned provider cell-grid enrollment')
    expect(result.qrCode).toMatch(/^data:image\/svg\+xml;base64,/)
    const image = Buffer.from(result.qrCode.split(',')[1], 'base64').toString('utf8')
    expect(image.match(/<rect /g)).toHaveLength(modules * modules)
    expect(image).toContain('style="fill:black;stroke:none"')
    expect(image).toContain('style="fill:white;stroke:none"')
    expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
    expect(mocks.unenroll).not.toHaveBeenCalled()
  })

  it.each([
    'https://collector.example.invalid/private-qr',
    '<svg onload="alert(1)"></svg>',
    '<svg><script>alert(1)</script></svg>',
    '<svg><foreignObject>content</foreignObject></svg>',
    '<svg><image href="https://collector.example.invalid"/></svg>',
    '<!DOCTYPE svg [<!ENTITY key SYSTEM "file:///private">]><svg></svg>',
    '<svg><path fill="url(https://collector.example.invalid)"/></svg>',
    '<svg>' + ' '.repeat(1_048_576) + '</svg>',
  ])('refuses an unsafe, remote or oversized provider QR', async qr => {
    mocks.enroll.mockResolvedValue({ data: enrolledData(qr), error: null })
    const result = await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))
    expect(result).toMatchObject({ status: 'error' })
    expect(result).not.toHaveProperty('qrCode')
    expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
    expect(mocks.unenroll).not.toHaveBeenCalled()
  })

  it.each([
    '<script>alert(1)</script>',
    '<image href="https://collector.example.invalid/private-qr"/>',
  ])('still rejects unsafe content inside a normally sized provider QR', async content => {
    const qr = `data:image/svg+xml;utf-8,${providerCellGrid(61).replace('</svg>', `${content}</svg>`)}`
    expect(qr.length).toBeGreaterThan(256_000)
    expect(qr.length).toBeLessThan(1_048_576)
    mocks.enroll.mockResolvedValue({ data: enrolledData(qr), error: null })
    const result = await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))
    expect(result.status).toBe('error')
    expect(result).not.toHaveProperty('qrCode')
    expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
    expect(mocks.unenroll).not.toHaveBeenCalled()
  })

  it('requires fresh live AAL2 before adding a factor to an already protected account', async () => {
    mocks.factors[0].status = 'verified'
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'Backup app' }))).toMatchObject({ status: 'error' })
    expect(mocks.enroll).not.toHaveBeenCalled()
    mocks.token = UPGRADED
    mocks.rpc.mockResolvedValue({ data: false, error: null })
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'Backup app' }))).toMatchObject({ status: 'error' })
    expect(mocks.enroll).not.toHaveBeenCalled()
    mocks.rpc.mockResolvedValue({ data: true, error: null })
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'Backup app' }))).toMatchObject({ status: 'enrolled' })
  })

  it('refuses a returned factor that is not in the current owner’s list', async () => {
    mocks.enroll.mockResolvedValue({ data: enrolledData(), error: null })
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))).toMatchObject({ status: 'error' })
  })

  it.each(['mfa_totp_enroll_not_enabled', 'mfa_factor_name_conflict', 'too_many_enrolled_mfa_factors'])(
    'shows a truthful provider refusal without echoing its details (%s)', async code => {
      mocks.enroll.mockResolvedValue({ data: null, error: { code, message: PRIVATE_DETAIL } })
      const result = await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))
      expect(result.status).toBe('error')
      expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
    },
  )

  it('validates names on the server and cannot enable local, signed-out or nonstaff accounts', async () => {
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'x'.repeat(61) }))).toMatchObject({
      status: 'error', fieldErrors: { friendlyName: expect.any(String) },
    })
    expect(mocks.createServerClient).not.toHaveBeenCalled()
    mocks.getStaffAssurance.mockResolvedValue({ state: 'not_staff', userId: USER })
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))).toMatchObject({ status: 'error' })
    mocks.getStaffAssurance.mockResolvedValue({ state: 'signed_out' })
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))).toMatchObject({ status: 'error' })
    mocks.local = true
    mocks.getStaffAssurance.mockResolvedValue({ state: 'local_unsupported', userId: 'usr_fixture' })
    expect(await actions.enrollStaffMfaAction(form({ friendlyName: 'Work phone' }))).toMatchObject({
      status: 'error', message: expect.stringContaining('no MFA'),
    })
    expect(mocks.enroll).not.toHaveBeenCalled()
  })
})

describe('fresh challenge, verified subject/session, persistence and fail-closed assurance', () => {
  it('uses the provider challenge, ignores forged identity/challenge/AAL input and confirms persisted AAL2', async () => {
    const result = await actions.verifyStaffMfaAction(form({
      factorId: FACTOR, code: '123456', userId: OTHER,
      challengeId: OTHER, expires_at: String(NOW + 99999), aal: 'aal2', qrCode: PRIVATE_DETAIL,
    }))
    expect(result.status).toBe('verified')
    expect(mocks.challenge).toHaveBeenCalledWith({ factorId: FACTOR })
    expect(mocks.verify).toHaveBeenCalledWith({ factorId: FACTOR, challengeId: CHALLENGE, code: '123456' })
    expect(mocks.getUser).toHaveBeenCalledWith(UPGRADED)
    expect(mocks.getClaims).toHaveBeenCalledWith(UPGRADED)
    expect(mocks.setCookie).toHaveBeenCalledWith('sb-fixture-auth-token', 'synthetic-session-cookie', { path: '/' })
    expect(mocks.rpc).toHaveBeenCalledWith('staff_session_assured')
    expect(JSON.stringify(result)).not.toContain('123456')
    expect(JSON.stringify(result)).not.toContain(UPGRADED)
    expect(JSON.stringify(result)).not.toContain('synthetic-refresh-token')
    expect(mocks.unenroll).not.toHaveBeenCalled()
  })

  it.each(['', '12345', '1234567', 'abcdef', '12 345', '１２３４５６'])('rejects malformed OTP input on the server', async code => {
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code }))).toMatchObject({
      status: 'error', fieldErrors: { code: expect.any(String) },
    })
    expect(mocks.getStaffAssurance).not.toHaveBeenCalled()
    expect(mocks.challenge).not.toHaveBeenCalled()
    expect(mocks.verify).not.toHaveBeenCalled()
  })

  it('rejects foreign factors and cannot verify an unfinished replacement from AAL1', async () => {
    expect(await actions.verifyStaffMfaAction(form({ factorId: OTHER, code: '123456' }))).toMatchObject({
      status: 'error', fieldErrors: { factorId: expect.any(String) },
    })
    expect(mocks.challenge).not.toHaveBeenCalled()
    mocks.factors.push({ id: NEW_FACTOR, factor_type: 'totp', status: 'verified', friendly_name: 'Existing app' })
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({ status: 'error' })
    expect(mocks.challenge).not.toHaveBeenCalled()
    expect(await actions.verifyStaffMfaAction(form({ factorId: NEW_FACTOR, code: '123456' }))).toMatchObject({ status: 'verified' })
  })

  it.each([
    { id: CHALLENGE, type: 'totp', expires_at: NOW },
    { id: CHALLENGE, type: 'totp', expires_at: 'later' },
    { id: 'forged-challenge', type: 'totp', expires_at: NOW + 300 },
    { id: CHALLENGE, type: 'phone', expires_at: NOW + 300 },
  ])('will not redeem a missing, expired or wrong-type provider challenge', async data => {
    mocks.challenge.mockResolvedValue({ data, error: null })
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({ status: 'error' })
    expect(mocks.verify).not.toHaveBeenCalled()
  })

  it.each(['mfa_verification_failed', 'mfa_totp_verify_not_enabled', 'mfa_challenge_expired', 'mfa_ip_address_mismatch'])(
    'handles rejected/expired/replayed provider verification without a success grant (%s)', async code => {
      mocks.verify.mockResolvedValue({ data: null, error: { code, message: PRIVATE_DETAIL } })
      const result = await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))
      expect(result.status).toBe('error')
      expect(mocks.rpc).not.toHaveBeenCalled()
      expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
      expect(JSON.stringify(result)).not.toContain('123456')
    },
  )

  it.each([
    { sub: OTHER },
    { session_id: OTHER },
    { aal: 'aal1' },
    { exp: NOW },
    { iat: NOW - 31 },
    { amr: [{ method: 'totp', timestamp: NOW - 31 }] },
    { amr: [{ method: 'password', timestamp: NOW }] },
    { amr: [{ method: 'webauthn', timestamp: NOW }] },
  ])('cannot claim staff success using a mismatched or preexisting returned MFA session (%j)', async override => {
    mocks.afterClaims = override
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({
      status: 'verified_unassured', message: expect.stringContaining('remains blocked'),
    })
    expect(mocks.rpc).not.toHaveBeenCalled()
  })

  it('does not replace session identity using a different provider user after verification', async () => {
    mocks.getUser.mockImplementation(async (token: string) => ({
      data: { user: { id: token === UPGRADED ? OTHER : USER } }, error: null,
    }))
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({ status: 'verified_unassured' })
    expect(mocks.rpc).not.toHaveBeenCalled()
  })

  it('requires the accepted factor still be verified and owned after verification', async () => {
    mocks.verify.mockImplementation(async () => {
      const result = await acceptCode()
      mocks.factors = []
      return result
    })
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({ status: 'verified_unassured' })
    expect(mocks.rpc).not.toHaveBeenCalled()
  })

  it.each([false, null])('does not grant assurance when the real session RPC returns %j', async data => {
    mocks.rpc.mockResolvedValue({ data, error: null })
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({
      status: 'verified_unassured', message: expect.stringContaining('remains blocked'),
    })
  })

  it('reports missing main migration distinctly from an unaccepted authenticator', async () => {
    mocks.rpc.mockResolvedValue({ data: null, error: { code: 'PGRST202', message: PRIVATE_DETAIL } })
    const result = await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))
    expect(result.status).toBe('verified_unassured')
    expect(result.message).toContain('provider accepted')
    expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
  })

  it('requires an actual MFA cookie write, not just an SDK in-memory session', async () => {
    mocks.verify.mockImplementation(async () => acceptCode(FACTOR, false))
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({ status: 'verified_unassured' })
    expect(mocks.rpc).not.toHaveBeenCalled()
  })

  it('tracks cookie-write failure even if an SDK subscriber swallows the exception', async () => {
    mocks.setCookie.mockImplementation(() => { throw new Error(PRIVATE_DETAIL) })
    mocks.verify.mockImplementation(async () => {
      try { await acceptCode() } catch { /* Simulate an SDK subscriber swallowing an adapter error. */ }
      return { data: verifiedData(), error: null }
    })
    const result = await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))
    expect(result.status).toBe('verified_unassured')
    expect(JSON.stringify(result)).not.toContain(PRIVATE_DETAIL)
    expect(mocks.rpc).not.toHaveBeenCalled()
  })

  it('revalidates roles after code acceptance rather than keeping a removed staff role', async () => {
    mocks.eq.mockResolvedValueOnce({ data: [{ role: 'admin' }], error: null })
      .mockResolvedValueOnce({ data: [], error: null })
    expect(await actions.verifyStaffMfaAction(form({ factorId: FACTOR, code: '123456' }))).toMatchObject({ status: 'verified_unassured' })
    expect(mocks.rpc).not.toHaveBeenCalled()
  })
})
