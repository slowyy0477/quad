/** Match the provider's per-cell SVGo format, without any real setup secret. */
function providerCellGrid(modules: number) {
  const size = (modules + 8) * 3
  const cells: string[] = []
  for (let row = 0; row < modules; row++) {
    for (let column = 0; column < modules; column++) {
      const fill = (row + column) % 2 ? 'black' : 'white'
      cells.push(`<rect x="${(column + 4) * 3}" y="${(row + 4) * 3}" width="3" height="3" style="fill:${fill};stroke:none" />\n`)
    }
  }
  return `<?xml version="1.0"?>\n<!-- Generated by SVGo -->\n<svg width="${size}" height="${size}" xmlns="http://www.w3.org/2000/svg" xmlns:xlink="http://www.w3.org/1999/xlink">\n${cells.join('')}</svg>\n`
}

function form(values: Record<string, string>) {
  const data = new FormData()
  for (const [name, value] of Object.entries(values)) data.set(name, value)
  return data
}
function proof(token: string) {
  return {
    sub: USER, role: 'authenticated', aud: 'authenticated',
    iss: 'https://mfa-fixture.supabase.invalid/auth/v1',
    session_id: SESSION, iat: NOW, exp: NOW + 600,
    aal: token === UPGRADED ? 'aal2' : 'aal1',
    amr: [{ method: token === UPGRADED ? 'totp' : 'password', timestamp: NOW }],
    ...(token === UPGRADED ? mocks.afterClaims : {}),
  }
}
function enrolledData(qr = `data:image/svg+xml;utf-8,${PROVIDER_SVG}`) {
  return {
    id: NEW_FACTOR, type: 'totp',
    totp: { qr_code: qr, secret: PRIVATE_DETAIL, uri: `otpauth://totp/fixture?secret=${PRIVATE_DETAIL}` },
  }
}
function verifiedData() {
  return {
    access_token: UPGRADED, refresh_token: 'synthetic-refresh-token', token_type: 'bearer',
    expires_in: 600, user: { id: USER },
  }
}
async function acceptCode(factorId = FACTOR, persist = true) {
  mocks.token = UPGRADED
  mocks.factors = mocks.factors.map(factor => factor.id === factorId ? { ...factor, status: 'verified' as const } : factor)
  if (persist) {
    mocks.adapter?.setAll([{ name: 'sb-fixture-auth-token', value: 'synthetic-session-cookie', options: { path: '/' } }])
  }
  return { data: verifiedData(), error: null }
}

