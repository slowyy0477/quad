#!/usr/bin/env node
/**
 * Provision a site administrator in the local store.
 *
 * The seed creates students and a demo account. It deliberately does not create a
 * staff account, for the same reason the migrations make `user_roles` writable by
 * nobody: an account that can read every report, audit row and bug report should
 * be a decision somebody made, once, with a password nobody typed into a file that
 * gets committed.
 *
 *   node scripts/local/make-admin.mjs
 *   node scripts/local/make-admin.mjs --email me@example.com --username boss --reset
 *
 * The password is generated here, hashed with the same scrypt parameters the app
 * uses, and written only as a hash. The plaintext goes to the credentials folder
 * outside the repository, with a warning on the file itself.
 *
 * Running it twice with `--reset` rotates the password; without it, an existing
 * administrator is left alone and the command says so.
 */
import { randomBytes, scryptSync } from 'node:crypto'
import fs from 'node:fs/promises'
import { existsSync } from 'node:fs'
import path from 'node:path'

const REPO = process.cwd()
const STORE = path.join(REPO, 'data', 'local.json')
const CREDENTIALS_DIR = process.env.QUAD_CREDENTIALS_DIR ?? 'D:\\Quad\\credentials'

const args = process.argv.slice(2)
const flag = (name, fallback) => {
  const index = args.indexOf(`--${name}`)
  return index >= 0 && args[index + 1] ? args[index + 1] : fallback
}

const EMAIL = flag('email', 'admin@quad.local').toLowerCase()
const USERNAME = flag('username', 'admin')
const DISPLAY_NAME = flag('display-name', 'Site Administrator')
const RESET = args.includes('--reset')

/** Same format as src/lib/local/session.ts: scrypt$<salt hex>$<key hex>. */
function hashPassword(password) {
  const salt = randomBytes(16).toString('hex')
  const derived = scryptSync(password, salt, 64).toString('hex')
  return `scrypt$${salt}$${derived}`
}

/**
 * 24 characters from an alphabet without look-alikes (no l, 1, O, 0), grouped for
 * reading aloud. ~124 bits: not guessable, and short enough to type once.
 */
function generatePassword() {
  const alphabet = 'ABCDEFGHJKMNPQRSTUVWXYZabcdefghijkmnpqrstuvwxyz23456789'
  const bytes = randomBytes(24)
  const chars = Array.from(bytes, (byte) => alphabet[byte % alphabet.length])
  return [chars.slice(0, 6).join(''), chars.slice(6, 12).join(''), chars.slice(12, 18).join(''), chars.slice(18, 24).join('')].join('-')
}

function id(prefix) {
  const random = Math.random().toString(36).slice(2, 10)
  return `${prefix}_${Date.now().toString(36)}${random}`
}

async function main() {
  if (!existsSync(STORE)) {
    console.error(`No store at ${STORE}. Start the app once (or reset the seed) so the store exists.`)
    process.exit(1)
  }

  const db = JSON.parse(await fs.readFile(STORE, 'utf8'))
  db.users ??= []
  db.profiles ??= []
  db.user_roles ??= []

  const existingUser = db.users.find((user) => user.email === EMAIL)
  const existingRole = existingUser
    ? db.user_roles.find((role) => role.user_id === existingUser.id && role.role === 'admin')
    : null

  if (existingUser && !RESET) {
    console.log(`${EMAIL} already exists and already holds the admin role.`)
    console.log('Use --reset to choose a new password for it.')
    return
  }

  const password = generatePassword()
  const passwordHash = hashPassword(password)
  const now = new Date().toISOString()

  let userId = existingUser?.id
  if (existingUser) {
    existingUser.password_hash = passwordHash
  } else {
    userId = id('usr')
    db.users.push({ id: userId, email: EMAIL, password_hash: passwordHash, created_at: now })
  }

  const profile = db.profiles.find((row) => row.user_id === userId)
  if (!profile) {
    db.profiles.push({
      id: id('prf'),
      user_id: userId,
      username: USERNAME,
      display_name: DISPLAY_NAME,
      bio: null,
      avatar_url: null,
      university_id: null,
      department: null,
      programme: null,
      semester: null,
      website: null,
      github: null,
      visibility: 'private',
      searchable: false,
      created_at: now,
    })
  }

  if (!db.user_roles.some((role) => role.user_id === userId && role.role === 'admin')) {
    db.user_roles.push({ id: id('rol'), user_id: userId, role: 'admin', created_at: now })
  }

  await fs.writeFile(STORE, JSON.stringify(db, null, 2), 'utf8')

  await fs.mkdir(CREDENTIALS_DIR, { recursive: true })
  const credentialsFile = path.join(CREDENTIALS_DIR, 'quad-admin.txt')
  const contents = [
    'Quad — site administrator',
    'Generated by scripts/local/make-admin.mjs',
    '',
    `email:    ${EMAIL}`,
    `password: ${password}`,
    `username: ${USERNAME}`,
    `store:    ${STORE}`,
    `created:  ${now}`,
    ...(RESET ? ['', 'This password replaced the previous one.'] : []),
    '',
    'This file is the only copy of the password. Keep it off any drive you sync or',
    'share. Delete it once the password is in your password manager — the app only',
    'stores a scrypt hash, so a lost password can only be replaced, never recovered.',
    '',
  ].join('\n')

  await fs.writeFile(credentialsFile, contents, { encoding: 'utf8', mode: 0o600 })

  console.log(`Administrator ready: ${EMAIL} (username ${USERNAME})`)
  console.log(`Password written to: ${credentialsFile}`)
  console.log('Sign in, then open /admin/data. Change the password in /settings if you want your own.')
}

main().catch((error) => {
  console.error('FAILED:', error)
  process.exit(1)
})
