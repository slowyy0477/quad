/**
 * Bundle every migration into one file that can be pasted into the Supabase SQL
 * editor.
 *
 * The normal way to apply migrations is `npm run db:push`, which needs the CLI
 * logged in and the database password to hand. This exists for the case where
 * that is a wall -- a first-time setup, a machine without the CLI -- because
 * "paste this into the dashboard and press Run" has no prerequisites at all.
 *
 * Two things make the output safe to run:
 *
 *   * It is wrapped in `begin` / `commit`. DDL is transactional in Postgres, so
 *     the whole schema either applies or nothing does. A half-applied schema is
 *     the worst outcome here -- migration 7 assumes migration 6 succeeded -- and
 *     this removes that state entirely.
 *
 *   * It records each file in `supabase_migrations.schema_migrations`, the table
 *     the CLI reads to decide what still needs applying. Without this, a later
 *     `db push` would try to re-run all 15 files and fail on the first `create
 *     table`. With it, the CLI agrees with reality and future migrations work
 *     normally.
 *
 * Regenerate after adding a migration:  node scripts/bundle-migrations.mjs
 *
 * Once the schema is already applied, re-running the whole file fails on the
 * first `create table` -- so pass `--from` to bundle only what is outstanding:
 *
 *   node scripts/bundle-migrations.mjs --from 0016   -> supabase/apply-from-0016.sql
 */
import { readFileSync, readdirSync, writeFileSync } from 'node:fs'
import { join } from 'node:path'

const MIGRATIONS_DIR = 'supabase/migrations'

// --from <version> | --from=<version>. Compared as a string prefix against the
// filename, which works because the numeric prefixes are fixed width.
const argv = process.argv.slice(2)
const fromIndex = argv.findIndex((a) => a === '--from' || a.startsWith('--from='))
const from = fromIndex === -1
  ? null
  : (argv[fromIndex].includes('=') ? argv[fromIndex].split('=')[1] : argv[fromIndex + 1])

if (fromIndex !== -1 && !from) {
  console.error('--from needs a version, e.g. --from 0016')
  process.exit(1)
}

const OUTPUT = from ? `supabase/apply-from-${from}.sql` : 'supabase/apply-all.sql'

const all = readdirSync(MIGRATIONS_DIR)
  .filter((name) => name.endsWith('.sql'))
  .sort() // filename order IS apply order; the numeric prefixes guarantee it

const files = from ? all.filter((name) => name >= from) : all

if (all.length === 0) {
  console.error('No migrations found.')
  process.exit(1)
}

if (files.length === 0) {
  console.error(`No migrations at or after "${from}". Found: ${all.join(', ')}`)
  process.exit(1)
}

const parts = [
  '-- ===========================================================================',
  from
    ? `-- Quad -- migrations from ${from} onwards, generated by scripts/bundle-migrations.mjs`
    : '-- Quad -- complete schema, generated by scripts/bundle-migrations.mjs',
  '--',
  `-- ${files.length} migration${files.length === 1 ? '' : 's'}, applied in one transaction.`,
  '--',
  '-- Paste the whole file into the Supabase SQL editor and press Run. If it',
  '-- errors, nothing is applied and the database is untouched -- read the error,',
  '-- fix the cause, and run it again.',
  '--',
  '-- DO NOT EDIT. Edit the migration files and regenerate.',
  '-- ===========================================================================',
  '',
  'begin;',
  '',
]

for (const name of files) {
  const sql = readFileSync(join(MIGRATIONS_DIR, name), 'utf8')
  parts.push(
    '',
    `-- ####### ${name} #######`,
    '',
    sql.trimEnd(),
    '',
  )
}

// The version is the filename with the .sql removed, which is what the CLI
// compares against. `on conflict do nothing` so re-running is harmless.
const versions = files.map((name) => `('${name.replace(/\.sql$/, '')}')`).join(',\n  ')

parts.push(
  '',
  '-- ####### Tell the Supabase CLI these have been applied #######',
  '--',
  '-- Otherwise the next `supabase db push` re-runs all of them and fails.',
  '--',
  '-- The table is created here rather than assumed. On a project that has never',
  '-- been touched by the CLI it does not exist yet -- the CLI creates it on its',
  '-- first push -- and assuming it does is an error that aborts the whole',
  '-- transaction at the very last statement. The column list matches what the CLI',
  '-- expects; `statements` and `name` are nullable and it fills them in itself.',
  '',
  'create schema if not exists supabase_migrations;',
  '',
  'create table if not exists supabase_migrations.schema_migrations (',
  '  version    text not null primary key,',
  '  statements text[],',
  '  name       text',
  ');',
  '',
  'insert into supabase_migrations.schema_migrations (version)',
  'values',
  `  ${versions}`,
  'on conflict (version) do nothing;',
  '',
  'commit;',
  '',
)

const output = parts.join('\n')
writeFileSync(OUTPUT, output)

const lines = output.split('\n').length
console.log(`Wrote ${OUTPUT} — ${files.length} migrations, ${lines} lines, ${(output.length / 1024).toFixed(0)} KB`)
