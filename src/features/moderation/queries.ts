type RawUniversityRow = {
  id: string
  name: string
  slug: string
  country: string | null
  city: string | null
  website: string | null
  created_at: string
  submitted_by: string | null
}

/** Requests waiting for a moderator, oldest first: first in, first decided. */
export async function getPendingUniversities({
  page = 1,
  perPage = ADMIN_PAGE_SIZE,
}: { page?: number; perPage?: number } = {}): Promise<ReadResult<PendingUniversity[]>> {
  const supabase = await createClient()
  const from = Math.max(0, page - 1) * perPage

  const { data, count, error } = await supabase
    .from('universities')
    .select('id, name, slug, country, city, website, created_at, submitted_by', { count: 'exact' })
    .eq('status', 'pending')
    .order('created_at', { ascending: true })
    .range(from, from + perPage - 1)
    .returns<RawUniversityRow[]>()

  if (error) {
    console.error('[moderation:getPendingUniversities]', error.code, error.message)
    return { rows: null, total: 0, error: READ_FAILED }
  }

  const raw = data ?? []

  // universities.submitted_by references auth.users, not profiles, so PostgREST
  // cannot embed the profile. Resolved in one extra query instead.
  const ids = [...new Set(raw.map((row) => row.submitted_by).filter((id): id is string => Boolean(id)))]
  const index =
    ids.length > 0
      ? buildPersonIndex(
          (
            await supabase
              .from('profiles')
              .select('id, username, display_name')
              .in('id', ids)
              .returns<RawPerson[]>()
          ).data ?? [],
        )
      : new Map<string, PersonRef>()

  const rows: PendingUniversity[] = raw.map((row) => ({
    id: row.id,
    name: row.name,
    slug: row.slug,
    country: row.country,
    city: row.city,
    website: row.website,
    createdAt: row.created_at,
    submittedBy: row.submitted_by ? index.get(row.submitted_by) ?? null : null,
  }))

  return { rows, total: count ?? rows.length, error: null }
}

