/**
 * Moderation reads — the queue, the audit log and pending university requests.
 *
 * These run as the signed-in moderator, so row level security decides what is in
 * them. That is not incidental: `reports`, `moderation_actions` and the narrow
 * policy on `messages` are what make these queries return anything at all, and
 * there is deliberately no TypeScript filter repeating those rules. A second copy
 * of an authorisation rule can only drift from the first, and when it drifts the
 * weaker copy wins — see the note at the top of features/feed/queries.ts.
 *
 * Pagination is offset-based, which ARCHITECTURE §6 permits for admin tables
 * only. A moderator queue is a bounded list somebody works through; a page number
 * is genuinely more useful there than a cursor, and the rows are not being
 * written to while they are read in the way a feed is.
 */

/** A person, as rendered in a queue row. */
export type PersonRef = {
  id: string
  username: string
  displayName: string
}

/** The reported thing, in the shape the queue renders it. */
export type ReportTarget =
  | {
      kind: 'post'
      id: string
      body: string | null
      createdAt: string
      moderationStatus: string
      author: PersonRef | null
    }
  | {
      kind: 'comment'
      id: string
      body: string | null
      createdAt: string
      moderationStatus: string
      author: PersonRef | null
      postId: string
    }
  | {
      kind: 'project'
      id: string
      title: string
      tagline: string | null
      slug: string
      moderationStatus: string
      author: PersonRef | null
    }
  | {
      kind: 'idea'
      id: string
      title: string
      description: string
      moderationStatus: string
      author: PersonRef | null
    }
  | {
      kind: 'message'
      id: string
      body: string | null
      createdAt: string
      moderationStatus: string
    }
  | {
      kind: 'profile'
      id: string
      person: PersonRef | null
      status: string
    }

export type QueueReport = {
  id: string
  kind: ReportKind
  reason: string
  detail: string | null
  createdAt: string
  reporter: PersonRef | null
  /** The person answerable for what was reported. Null when they deleted it. */
  reported: PersonRef | null
  target: ReportTarget
}

export type ModerationActionRow = {
  id: string
  action: string
  reason: string
  createdAt: string
  actor: PersonRef | null
  target: PersonRef | null
  reportId: string | null
  university: string | null
  supersedesId: string | null
  /** What the action applied to, as a noun phrase. Never the content itself. */
  subject: string | null
}

export type PendingUniversity = {
  id: string
  name: string
  slug: string
  country: string | null
  city: string | null
  website: string | null
  createdAt: string
  /** Resolved separately: universities.submitted_by references auth.users. */
  submittedBy: PersonRef | null
}

export const ADMIN_PAGE_SIZE = 25

type ReadResult<T> = { rows: T; total: number; error: null } | { rows: null; total: 0; error: string }

const READ_FAILED = 'That list could not be loaded. Please try again.'

// ---------------------------------------------------------------------------
// Raw shapes as PostgREST returns them. The generated database types do not
// contain `reports`, `moderation_actions` or `bug_reports` yet -- the file is
// derived from the migrations and is regenerated by the maintainer -- so these
// local types stand in until `npm run db:types` runs. They are hand-written from
// the migration, and the alternative (casting rows to `any` throughout) would
// move the same risk somewhere invisible.
// ---------------------------------------------------------------------------

type RawPerson = { id: string; username: string; display_name: string }

type RawQueueRow = {
  id: string
  kind: ReportKind
  reason: string
  detail: string | null
  created_at: string
  reporter_id: string
  post: { id: string; body: string | null; created_at: string; moderation_status: string; author_id: string } | null
  comment:
    | { id: string; body: string | null; created_at: string; post_id: string; moderation_status: string; author_id: string }
    | null
  project: { id: string; title: string; tagline: string | null; slug: string; moderation_status: string; owner_id: string } | null
  idea: { id: string; title: string; description: string; moderation_status: string; author_id: string } | null
  message: { id: string; body: string | null; created_at: string; moderation_status: string; sender_id: string } | null
  target_profile: RawPerson | null
}

/**
 * The queue select.
 *
 * The target tables are embedded rather than fetched in six follow-up queries,
 * and their nested authors are *not* embedded — the author ids come back flat and
 * are resolved in one extra profiles query below. Two reasons: a nested embed is
 * the part of PostgREST's query language most likely to be got subtly wrong, and a
 * profiles query with `.in('id', …)` is one round trip for every row on the page
 * instead of one per row.
 *
 * A message appears here only when it has been reported, which is the narrow
 * moderator read added to `messages` in 0020.
 */
const QUEUE_SELECT = `
  id, kind, reason, detail, created_at, reporter_id,
  post:posts ( id, body, created_at, moderation_status, author_id ),
  comment:comments ( id, body, created_at, post_id, moderation_status, author_id ),
  project:projects ( id, title, tagline, slug, moderation_status, owner_id ),
  idea:ideas ( id, title, description, moderation_status, author_id ),
  message:messages ( id, body, created_at, moderation_status, sender_id ),
  target_profile:profiles!reports_user_id_fkey ( id, username, display_name )
`

function personOf(row: RawPerson | null | undefined, index: Map<string, PersonRef>): PersonRef | null {
  if (!row) return null
  return index.get(row.id) ?? { id: row.id, username: row.username, displayName: row.display_name }
}

/** Open reports, newest first. */
export async function getOpenReports({
  page = 1,
  perPage = ADMIN_PAGE_SIZE,
}: { page?: number; perPage?: number } = {}): Promise<ReadResult<QueueReport[]>> {
  if (isLocalMode()) {
    // The store has a `reports` table, but nothing in local mode writes to it: the
    // report flow, the moderation decisions and the append-only audit log are one
    // unit and none of them is ported. Returning the real rows here without the
    // decision machinery would offer a queue whose buttons cannot work, so this
    // says "nothing is waiting" — which is true — rather than half-building it.
    return { rows: [], total: 0, error: null }
  }

  const supabase = await createClient()
  const from = Math.max(0, page - 1) * perPage

  const { data, count, error } = await supabase
    .from('reports')
    .select(QUEUE_SELECT, { count: 'exact' })
    .eq('status', 'open')
    .order('created_at', { ascending: false })
    .order('id', { ascending: false })
    .range(from, from + perPage - 1)
    .returns<RawQueueRow[]>()

  if (error) {
    console.error('[moderation:getOpenReports]', error.code, error.message)
    return { rows: null, total: 0, error: READ_FAILED }
  }

  const raw = data ?? []

  // One query for every person on the page: the reporters, the authors of the
  // reported content, and the reported profiles.
  const ids = new Set<string>()
  for (const row of raw) {
    ids.add(row.reporter_id)
    if (row.target_profile) ids.add(row.target_profile.id)
    if (row.post) ids.add(row.post.author_id)
    if (row.comment) ids.add(row.comment.author_id)
    if (row.project) ids.add(row.project.owner_id)
    if (row.idea) ids.add(row.idea.author_id)
    if (row.message) ids.add(row.message.sender_id)
  }

  const index = buildPersonIndex(
    ids.size > 0
      ? (
          await supabase
            .from('profiles')
            .select('id, username, display_name')
            .in('id', [...ids])
            .returns<RawPerson[]>()
        ).data ?? []
      : [],
  )

  const rows: QueueReport[] = []

  for (const row of raw) {
    const reporter = index.get(row.reporter_id) ?? null
    const target = buildTarget(row, index)
    if (!target) continue

    rows.push({
      id: row.id,
      kind: row.kind,
      reason: row.reason,
      detail: row.detail,
      createdAt: row.created_at,
      reporter,
      reported: targetAuthor(target),
      target,
    })
  }

  return { rows, total: count ?? rows.length, error: null }
}

function buildPersonIndex(rows: RawPerson[]): Map<string, PersonRef> {
  return new Map(
    rows.map((row) => [
      row.id,
      { id: row.id, username: row.username, displayName: row.display_name },
    ]),
  )
}

/**
 * Which person is answerable for the reported thing.
 *
 * Null for a message: the sender is deliberately not resolved here. A moderator
 * sees the message they were asked about, and identifying its author from the
 * queue would be a second, quieter way to browse the conversation — the author is
 * reachable through the report decision, which is audited.
 */
function targetAuthor(target: ReportTarget): PersonRef | null {
  if (target.kind === 'profile') return target.person
  if (target.kind === 'message') return null
  return target.author
}

function buildTarget(row: RawQueueRow, index: Map<string, PersonRef>): ReportTarget | null {
  switch (row.kind) {
    case 'post':
      if (!row.post) return null
      return {
        kind: 'post',
        id: row.post.id,
        body: row.post.body,
        createdAt: row.post.created_at,
        moderationStatus: row.post.moderation_status,
        author: index.get(row.post.author_id) ?? null,
      }
    case 'comment':
      if (!row.comment) return null
      return {
        kind: 'comment',
        id: row.comment.id,
        body: row.comment.body,
        createdAt: row.comment.created_at,
        moderationStatus: row.comment.moderation_status,
        author: index.get(row.comment.author_id) ?? null,
        postId: row.comment.post_id,
      }
    case 'project':
      if (!row.project) return null
      return {
        kind: 'project',
        id: row.project.id,
        title: row.project.title,
        tagline: row.project.tagline,
        slug: row.project.slug,
        moderationStatus: row.project.moderation_status,
        author: index.get(row.project.owner_id) ?? null,
      }
    case 'idea':
      if (!row.idea) return null
      return {
        kind: 'idea',
        id: row.idea.id,
        title: row.idea.title,
        description: row.idea.description,
        moderationStatus: row.idea.moderation_status,
        author: index.get(row.idea.author_id) ?? null,
      }
    case 'message':
      if (!row.message) return null
      return {
        kind: 'message',
        id: row.message.id,
        body: row.message.body,
        createdAt: row.message.created_at,
        moderationStatus: row.message.moderation_status,
      }
    case 'profile':
      if (!row.target_profile) return null
      return {
        kind: 'profile',
        id: row.target_profile.id,
        person: personOf(row.target_profile, index),
        status: 'active',
      }
  }
}

