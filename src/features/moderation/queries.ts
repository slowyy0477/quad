type RawActionRow = {
  id: string
  action: string
  reason: string
  created_at: string
  supersedes_id: string | null
  report_id: string | null
  university_id: string | null
  post_id: string | null
  comment_id: string | null
  project_id: string | null
  idea_id: string | null
  message_id: string | null
  actor: RawPerson | null
  target: RawPerson | null
  university: { name: string } | null
}

/** The audit log, newest first. Readable by moderators only, by policy. */
export async function getModerationActions({
  page = 1,
  perPage = ADMIN_PAGE_SIZE,
}: { page?: number; perPage?: number } = {}): Promise<ReadResult<ModerationActionRow[]>> {
  const supabase = await createClient()
  const from = Math.max(0, page - 1) * perPage

  const { data, count, error } = await supabase
    .from('moderation_actions')
    .select(
      `
        id, action, reason, created_at, supersedes_id,
        report_id, university_id, post_id, comment_id, project_id, idea_id, message_id,
        actor:profiles!moderation_actions_actor_id_fkey ( id, username, display_name ),
        target:profiles!moderation_actions_target_profile_id_fkey ( id, username, display_name ),
        university:universities!moderation_actions_university_id_fkey ( name )
      `,
      { count: 'exact' },
    )
    .order('created_at', { ascending: false })
    .order('id', { ascending: false })
    .range(from, from + perPage - 1)
    .returns<RawActionRow[]>()

  if (error) {
    console.error('[moderation:getModerationActions]', error.code, error.message)
    return { rows: null, total: 0, error: READ_FAILED }
  }

  const rows = (data ?? []).map((row) => ({
    id: row.id,
    action: row.action,
    reason: row.reason,
    createdAt: row.created_at,
    actor: row.actor
      ? { id: row.actor.id, username: row.actor.username, displayName: row.actor.display_name }
      : null,
    target: row.target
      ? { id: row.target.id, username: row.target.username, displayName: row.target.display_name }
      : null,
    reportId: row.report_id,
    university: row.university?.name ?? null,
    supersedesId: row.supersedes_id,
    subject: subjectOf(row),
  }))

  return { rows, total: count ?? rows.length, error: null }
}

/**
 * What the action applied to, as a phrase.
 *
 * Deliberately not the content. The log records what a moderator did and why; it
 * is not a second copy of what they moderated, and copying a hidden post into an
 * append-only table would make "removed" a lie.
 */
function subjectOf(row: RawActionRow): string | null {
  if (row.university_id) return 'a university request'
  if (row.post_id) return 'a post'
  if (row.comment_id) return 'a comment'
  if (row.project_id) return 'a project'
  if (row.idea_id) return 'an idea'
  if (row.message_id) return 'a message'
  return null
}

