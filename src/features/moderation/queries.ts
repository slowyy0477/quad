export type ModerationCounts = {
  openReports: number
  pendingUniversities: number
}

/**
 * The two numbers the admin shell shows.
 *
 * Both are `count(*)` over stored rows. There is no cached or remembered total:
 * a queue badge that disagrees with the queue is worse than no badge, and the
 * partial index on open reports makes the count cheap.
 */
export async function getModerationCounts(): Promise<ModerationCounts> {
  if (isLocalMode()) {
    const db = await readStore()
    // `reports` exists in the store; `universities.status` does not (the local
    // university rows have no review state), so there is never a pending one.
    return {
      openReports: db.reports.filter((report) => report.status === 'open').length,
      pendingUniversities: 0,
    }
  }

  const supabase = await createClient()

  const [reports, universities] = await Promise.all([
    supabase
      .from('reports')
      .select('id', { count: 'exact', head: true })
      .eq('status', 'open'),
    supabase
      .from('universities')
      .select('id', { count: 'exact', head: true })
      .eq('status', 'pending'),
  ])

  if (reports.error) console.error('[moderation:counts]', reports.error.code, reports.error.message)
  if (universities.error)
    console.error('[moderation:counts]', universities.error.code, universities.error.message)

  return {
    openReports: reports.count ?? 0,
    pendingUniversities: universities.count ?? 0,
  }
}

// ---------------------------------------------------------------------------
// A note on what is deliberately absent
// ---------------------------------------------------------------------------
//
// There is no "reports you have filed" query here, and its absence is a decision
// rather than an oversight. UX.md §4 specifies exactly three M7 surfaces, and a
// reporter's own list is not one of them; the reporter's feedback channel is the
// notification 0020 writes when a moderator decides (asserted in
// tests/db/moderation.test.ts), which arrives wherever the reader already is
// instead of requiring them to come back and check. A list that nobody is told
// about is a list nobody reads, and it would also be a second place where a
// dismissed report stays visible after the person who filed it has moved on.
//
// If a later milestone adds a "your reports" page under the profile, this is
// where the query belongs: `select id, kind, reason, status, created_at from
// public.reports order by created_at desc`, which `reports_select_own` already
// permits.
