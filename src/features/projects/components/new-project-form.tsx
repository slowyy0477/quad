'use client'

import { useActionState } from 'react'
import { Alert } from '@/components/ui/alert'
import { Checkbox } from '@/components/ui/checkbox'
import { Field } from '@/components/ui/field'
import { Input } from '@/components/ui/input'
import { SubmitButton } from '@/components/ui/submit-button'
import { createProjectAction } from '@/features/projects/actions'
import { emptyFormState } from '@/lib/form-state'

/**
 * Create a project.
 *
 * Three things are asked for, and each one is a column the database requires or the
 * team-finder reads: a title, a one-line purpose, and whether the project wants
 * members (with the size it is aiming for). Everything else on the row — the slug, the
 * owner, the university and the four counters — is generated by the insert trigger
 * from the session and the title, so it is not asked for and not sent.
 *
 * `category`, `status` and `visibility` ride along as hidden defaults. They are not
 * absent because they do not matter but because a first project should not demand
 * four decisions before it exists; the owner can change them from the project page.
 * `visibility` defaults to `public`, and the trigger silently clamps it down to
 * whatever the owner's profile allows, which is why the redirect can report a clamp.
 */
export function NewProjectForm() {
  const [state, action] = useActionState(createProjectAction, emptyFormState)

  return (
    <form action={action} className="space-y-6">
      {state.status === 'error' && state.message ? (
        <Alert tone="danger" title="The project was not created">
          {state.message}
        </Alert>
      ) : null}

      <input type="hidden" name="category" value="other" />
      <input type="hidden" name="status" value="planning" />
      <input type="hidden" name="visibility" value="public" />

      <Field
        id="title"
        label="Title"
        required
        hint="What the project is called. The web address is made from this."
        error={state.fieldErrors?.title}
      >
        {(props) => (
          <Input
            {...props}
            name="title"
            defaultValue={state.values?.title}
            maxLength={120}
            autoComplete="off"
            placeholder="Campus ride share"
          />
        )}
      </Field>

      <Field
        id="tagline"
        label="One-line purpose"
        hint="The sentence that appears under the title in lists. Up to 160 characters."
        error={state.fieldErrors?.tagline}
      >
        {(props) => (
          <Input
            {...props}
            name="tagline"
            defaultValue={state.values?.tagline}
            maxLength={160}
            placeholder="Matching students travelling the same way"
          />
        )}
      </Field>

      <fieldset className="space-y-4 rounded border border-hairline p-4">
        <legend className="px-1 text-sm font-medium text-ink">Seeking members</legend>

        <label htmlFor="isSeekingMembers" className="flex items-start gap-3">
          <span className="pt-0.5">
            <Checkbox
              id="isSeekingMembers"
              name="isSeekingMembers"
              defaultChecked={state.values?.isSeekingMembers === 'on'}
            />
          </span>
          <span>
            <span className="block text-sm text-ink">This project is looking for people</span>
            <span className="block text-xs text-ink-muted">
              It appears under “Open to join” until its slots are filled. A private project cannot
              advertise, and the database will turn this off if you make it private.
            </span>
          </span>
        </label>

        <Field
          id="teamSizeTarget"
          label="Team size you are aiming for"
          hint="Optional. When the member count reaches it, the project stops appearing in “Open to join” by itself."
          error={state.fieldErrors?.teamSizeTarget}
        >
          {(props) => (
            <Input
              {...props}
              name="teamSizeTarget"
              type="number"
              min={1}
              max={50}
              defaultValue={state.values?.teamSizeTarget}
              className="max-w-32"
            />
          )}
        </Field>
      </fieldset>

      <SubmitButton variant="primary" pendingLabel="Creating…">
        Create project
      </SubmitButton>
    </form>
  )
}
